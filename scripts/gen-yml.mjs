#!/usr/bin/env node
// Node 22 native ESM, zero dependencies.
// Scans apps/ and music/ and generates yingotab.yml (hand-rolled YAML output).
import { readdirSync, readFileSync, writeFileSync, existsSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();
const AUDIO_EXT = new Set(['.mp3', '.flac', '.ogg', '.m4a']);

// ---- helpers ----------------------------------------------------------

// Escape a string for single-quoted YAML: '' inside single quotes.
const yq = (s) => `'${String(s).replace(/'/g, "''")}'`;

const slugify = (name) =>
  name
    .replace(/\.[^.]+$/, '') // strip extension
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

const readJson = (p) => {
  try {
    return JSON.parse(readFileSync(p, 'utf8'));
  } catch {
    return null;
  }
};

// ---- apps -------------------------------------------------------------

const apps = [];
const appsDir = join(ROOT, 'apps');
if (existsSync(appsDir)) {
  for (const dir of readdirSync(appsDir, { withFileTypes: true })) {
    if (!dir.isDirectory()) continue;
    const slug = dir.name;
    const meta = readJson(join(appsDir, slug, 'app.json')) || {};
    apps.push({
      id: meta.id || slug,
      name: meta.name || slug,
      icon: meta.icon || '📦',
      type: meta.type || 'dock',
      entry: meta.entry || `apps/${slug}/index.html`,
    });
  }
}
apps.sort((a, b) => a.id.localeCompare(b.id));

// ---- music ------------------------------------------------------------

const music = [];
const musicDir = join(ROOT, 'music');
let musicMeta = {};
const metaPath = join(musicDir, 'music.json');
if (existsSync(metaPath)) {
  musicMeta = readJson(metaPath) || {};
}
if (existsSync(musicDir)) {
  for (const f of readdirSync(musicDir, { withFileTypes: true })) {
    if (!f.isFile()) continue;
    const ext = f.name.slice(f.name.lastIndexOf('.')).toLowerCase();
    if (!AUDIO_EXT.has(ext)) continue;
    const id = slugify(f.name);
    const meta = musicMeta[id] || {};
    music.push({
      id,
      title: meta.title || f.name.replace(/\.[^.]+$/, ''),
      artist: meta.artist || '',
      file: `music/${f.name}`,
    });
  }
}
music.sort((a, b) => a.id.localeCompare(b.id));

// ---- emit YAML --------------------------------------------------------

const lines = [];
lines.push('# generated by CI, do not edit');
lines.push('version: 1');
lines.push('apps:');
if (apps.length === 0) lines.push('  []');
for (const a of apps) {
  lines.push(`  - id: ${yq(a.id)}`);
  lines.push(`    name: ${yq(a.name)}`);
  lines.push(`    icon: ${yq(a.icon)}`);
  lines.push(`    type: ${yq(a.type)}`);
  lines.push(`    entry: ${yq(a.entry)}`);
}
lines.push('music:');
if (music.length === 0) lines.push('  []');
for (const m of music) {
  lines.push(`  - id: ${yq(m.id)}`);
  lines.push(`    title: ${yq(m.title)}`);
  lines.push(`    artist: ${yq(m.artist)}`);
  lines.push(`    file: ${yq(m.file)}`);
}
lines.push('widgets: []');

const out = lines.join('\n') + '\n';
writeFileSync(join(ROOT, 'yingotab.yml'), out);
console.log(`yingotab.yml written: ${apps.length} apps, ${music.length} music tracks`);
